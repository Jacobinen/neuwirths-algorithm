def _parse_cycles(s):
    """'(1,2)(3,4)' -> [[1, 2], [3, 4]], in the order written."""
    if s in ("", "()"):
        return []
    parts = s.split(")(")
    parts[0] = parts[0][1:]
    parts[-1] = parts[-1][:-1]
    return [[int(k) for k in c.split(",")] for c in parts]


def _orbits(perms, elements):
    """Orbits of the group generated by ``perms`` (dicts) on ``elements``."""
    seen = set()
    result = []
    for start in sorted(elements):
        if start in seen:
            continue
        orbit = [start]
        seen.add(start)
        for x in orbit:
            for p in perms:
                y = p[x]
                if y not in seen:
                    seen.add(y)
                    orbit.append(y)
        result.append(orbit)
    return result


def _cycles(perm, elements):
    """Cycles of the permutation ``perm`` (dict), each starting at its smallest element."""
    seen = set()
    result = []
    for start in sorted(elements):
        if start in seen:
            continue
        cycle = [start]
        seen.add(start)
        x = perm[start]
        while x != start:
            cycle.append(x)
            seen.add(x)
            x = perm[x]
        result.append(cycle)
    return result


def _link_cycle(triangles, node):
    """The link of ``node`` in a triangulated surface: its neighbours in cyclic order."""
    edges = {}
    for tri in triangles:
        if node in tri:
            a, b = [x for x in tri if x != node]
            edges.setdefault(a, []).append(b)
            edges.setdefault(b, []).append(a)
    start = next(iter(edges))
    cycle = [start]
    prev, cur = None, start
    while True:
        nxt = [x for x in edges[cur] if x != prev]
        nxt = nxt[0] if nxt else edges[cur][0]
        if nxt == start:
            break
        cycle.append(nxt)
        prev, cur = cur, nxt
    return cycle


def _tutte(adjacency, fixed):
    """Tutte embedding: every non-fixed node is placed at the average of its neighbours.

    ``adjacency`` maps a node to the list of its neighbours, ``fixed`` maps the boundary
    nodes to their positions.  The linear system is symmetric positive definite and is
    solved with conjugate gradients."""
    interior = [v for v in adjacency if v not in fixed]
    index = {v: k for k, v in enumerate(interior)}
    m = len(interior)
    if m == 0:
        return dict(fixed)
    deg = [len(adjacency[v]) for v in interior]
    neighbours = [[index[w] for w in adjacency[v] if w in index] for v in interior]
    rhs = []
    for v in interior:
        sx = sum(fixed[w][0] for w in adjacency[v] if w in fixed)
        sy = sum(fixed[w][1] for w in adjacency[v] if w in fixed)
        rhs.append((sx, sy))

    def matvec(x):
        return [deg[i] * x[i] - sum(x[j] for j in neighbours[i]) for i in range(m)]

    def solve(b):
        x = [0.0] * m
        r = list(b)
        p = list(r)
        rr = sum(ri * ri for ri in r)
        for _ in range(20 * m + 100):
            if rr < 1e-24:
                break
            ap = matvec(p)
            alpha = rr / sum(p[i] * ap[i] for i in range(m))
            for i in range(m):
                x[i] += alpha * p[i]
                r[i] -= alpha * ap[i]
            rr_new = sum(ri * ri for ri in r)
            beta = rr_new / rr
            rr = rr_new
            for i in range(m):
                p[i] = r[i] + beta * p[i]
        return x

    xs = solve([b[0] for b in rhs])
    ys = solve([b[1] for b in rhs])
    positions = dict(fixed)
    for v, k in index.items():
        positions[v] = (xs[k], ys[k])
    return positions


def _closest_point_on_segment(p, a, b):
    ax, ay = a
    bx, by = b
    px, py = p
    dx, dy = bx - ax, by - ay
    l2 = dx * dx + dy * dy
    if l2 == 0:
        return a, 0.0
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / l2))
    return (ax + t * dx, ay + t * dy), t


def _point_segment_distance(p, a, b):
    q, _ = _closest_point_on_segment(p, a, b)
    return math.hypot(p[0] - q[0], p[1] - q[1])


def _segments_cross(p1, p2, p3, p4):
    """Proper crossing of the segments p1p2 and p3p4 (touching endpoints do not count)."""
    def orient(a, b, c):
        return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
    d1 = orient(p3, p4, p1)
    d2 = orient(p3, p4, p2)
    d3 = orient(p1, p2, p3)
    d4 = orient(p1, p2, p4)
    return d1 * d2 < 0 and d3 * d4 < 0


def _chaikin(points, rounds=3):
    """Chaikin's corner cutting: a smooth curve that stays inside the corridor of the
    polyline (unlike a spline it never overshoots, so parallel strands stay apart)."""
    pts = list(points)
    if len(pts) < 3:
        return pts
    for _ in range(rounds):
        out = [pts[0]]
        for a, b in zip(pts, pts[1:]):
            out.append((0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]))
            out.append((0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]))
        out.append(pts[-1])
        pts = out
    return pts


def _catmull_rom(points, tension=0.5, samples=8):
    """Kept for compatibility: smoothing now uses Chaikin's corner cutting."""
    return _chaikin(points)


def _polyline_length(points):
    return sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(points, points[1:]))


def _polyline_point(points, fraction):
    """Point and unit tangent at the given fraction of the length of a polyline."""
    segments = list(zip(points, points[1:]))
    lengths = [math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in segments]
    target = fraction * sum(lengths)
    for k, ((a, b), l) in enumerate(zip(segments, lengths)):
        if target <= l or k == len(segments) - 1:
            t = min(1.0, target / l) if l else 0.0
            x, y = a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])
            tx, ty = ((b[0] - a[0]) / l, (b[1] - a[1]) / l) if l else (1.0, 0.0)
            return (x, y), (tx, ty)
        target -= l
    return points[-1], (1.0, 0.0)


def _turning(angles):
    """Total counter-clockwise turning when going through ``angles`` cyclically."""
    return sum((a2 - a1) % (2 * math.pi) for a1, a2 in zip(angles, angles[1:] + angles[:1]))


