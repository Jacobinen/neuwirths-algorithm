"""Planar Heegaard diagrams from the data of Neuwirth's algorithm.

When ``neuwirthcheck.find_2_spine`` finds a configuration (A, B, C) for a balanced
presentation ``<a_1, ..., a_g | r_1, ..., r_g>``, the triple describes a Heegaard
diagram of the 3-manifold that has the presentation complex as a spine.  This module
draws that diagram in the usual planar form: the genus-g surface is cut open along
the alpha-curves, which turns it into a sphere with 2g disks removed.  The two disks
``a_i`` and ``a_i-bar`` are the two sides of the cut along alpha_i, and their boundary
circles are identified so that the points carrying the same sheet number coincide.

* The points of E (the darts of Neuwirth's permutations) are the points where the
  beta-curves cross the alpha-curves: the j-th sheet of the generator ``a_i`` is the
  point ``j`` on the disk ``a_i`` and the point ``j`` on the disk ``a_i-bar``.  C is
  the counter-clockwise order of these points around each disk.
* A pairs the two ends of every arc of a beta-curve in the sphere; B pairs the two
  copies of the same point on ``a_i`` and ``a_i-bar`` (the piece of the beta-curve
  that runs through the handle).
* Reading the relator r_j along beta_j, the letter ``a_i`` is the passage from the
  disk ``a_i`` to the disk ``a_i-bar`` and ``a_i^-1`` the passage in the opposite
  direction.  The basepoint of beta_j (the "pointed" diagram of the paper) is marked
  on the arc between the last and the first letter of r_j.

Layout.  Bundles of parallel arcs (arcs that are consecutive around both of their
disks and bound bigons) are first contracted to single fat edges.  The reduced map is
embedded with a Tutte embedding of the second barycentric subdivision of its faces;
that subdivision is always a simple triangulation of the sphere, so the embedding is
planar even when the map has bridges, and the arcs leave every disk in exactly the
cyclic order C.  The embedding is then relaxed by a force-directed pass that moves the
disk centres, the angles at which the arcs leave the disks and three bend points per
arc; a move is only accepted if it creates no crossing and keeps the cyclic order at
every disk, and steps are kept small relative to the nearest other feature, so the
combinatorial embedding never changes while the picture spreads out.  Finally every
bundle is expanded into parallel strands and the full drawing is relaxed once more.

When the group generated by A and C has L > 1 orbits, the sphere is really L spheres
(one for each orbit); they are drawn side by side.  The algorithm then joins them by
tubes attached in one region of each sphere; these regions are marked with a star.
"""

