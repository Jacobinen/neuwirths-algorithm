class _Relaxer:
    """Force-directed refinement of a planar drawing of a map.

    The map is given by ``vertex_darts`` (the darts around every disk in counter-
    clockwise order), ``vertex_of`` (dart -> disk) and ``arc_darts`` (arc -> its two
    darts).  Every arc leaves its disk through a radial *port* at distance
    ``port_radius[v]`` from the centre; the free variables are the disk centres, the
    angle of every port and three middle bends per arc.  A move is accepted only if no
    two non-adjacent segments cross afterwards and the cyclic order of the ports around
    every disk is still the given one; moves are capped at a fraction of the distance
    to the nearest other feature so that nothing can jump over anything.  Port radii
    start tiny (the initial embedding is a Tutte embedding, which squeezes everything)
    and are inflated whenever that keeps the drawing valid.

    ``lane_count`` (dart -> number of parallel strands the arc stands for) lets the
    relaxer treat a contracted bundle as a fat edge: it gets a proportional share of the
    angle around its disks and extra clearance."""

    def __init__(self, vertex_darts, vertex_of, arc_darts, vpos, angles, bends, port_radius, rho,
                 lane_count=None, partners=(), sheet_partner=None):
        self.partners = {frozenset(pair) for pair in partners if len(set(pair)) == 2}
        self.sheet_partner = sheet_partner or {}
        self.vertex_darts = {v: list(ds) for v, ds in vertex_darts.items()}
        self.vertex_of = vertex_of
        self.arc_darts = dict(arc_darts)
        self.edge_of = {}
        for idx, (ea, eb) in self.arc_darts.items():
            self.edge_of[ea] = idx
            self.edge_of[eb] = idx
        self.vpos = vpos
        self.angles = angles
        self.bends = bends
        self.port_radius = port_radius
        self.rho = rho
        self.vertices = sorted(vpos)
        self.arcs = sorted(bends)
        self.arc_vertices = {idx: (vertex_of[ea], vertex_of[eb]) for idx, (ea, eb) in self.arc_darts.items()}
        self.lane_count = lane_count or {}
        self.width = {idx: (self.lane_count.get(ea, 1) - 1) / 2 * 0.8 * rho for idx, (ea, eb) in self.arc_darts.items()}
        self.nodes = ([("V", v) for v in self.vertices]
                      + [("D", e) for v in self.vertices for e in self.vertex_darts[v]]
                      + [("B", idx, k) for idx in self.arcs for k in range(3)])

    # -- geometry
    def port(self, e):
        v = self.vertex_of[e]
        cx, cy = self.vpos[v]
        r = self.port_radius[v]
        return (cx + r * math.cos(self.angles[e]), cy + r * math.sin(self.angles[e]))

    def arc_points(self, idx):
        """centre, port, b1, b2, b3, port, centre"""
        va, vb = self.arc_vertices[idx]
        ea, eb = self.arc_darts[idx]
        return [self.vpos[va], self.port(ea)] + list(self.bends[idx]) + [self.port(eb), self.vpos[vb]]

    def segment_nodes(self, idx, k):
        va, vb = self.arc_vertices[idx]
        ea, eb = self.arc_darts[idx]
        names = [("V", va), ("D", ea), ("B", idx, 0), ("B", idx, 1), ("B", idx, 2), ("D", eb), ("V", vb)]
        return names[k], names[k + 1]

    def segments(self):
        out = []
        for idx in self.arcs:
            pts = self.arc_points(idx)
            for k in range(6):
                out.append((idx, k, pts[k], pts[k + 1]))
        return out

    def incident_segments(self, node):
        if node[0] == "V":
            out = []
            for e in self.vertex_darts[node[1]]:
                out += self.incident_segments(("D", e))
            return out
        if node[0] == "D":
            e = node[1]
            idx = self.edge_of[e]
            return [(idx, 0), (idx, 1)] if self.arc_darts[idx][0] == e else [(idx, 4), (idx, 5)]
        idx, k = node[1], node[2]
        return [(idx, k + 1), (idx, k + 2)]

    def rotation_ok(self, v):
        darts = self.vertex_darts[v]
        if len(darts) < 3:
            return True
        return abs(_turning([self.angles[e] for e in darts]) - 2 * math.pi) < 1e-9

    def _adjacent(self, idx, k, idx2, k2):
        return bool(set(self.segment_nodes(idx, k)) & set(self.segment_nodes(idx2, k2)))

    def ends_ok(self, idx):
        """Do both ends of the arc leave their disks outwards (first bend outside the
        port circle and ahead of the port)?"""
        pts = self.arc_points(idx)
        for centre, port, bend, v in ((pts[0], pts[1], pts[2], self.arc_vertices[idx][0]),
                                      (pts[6], pts[5], pts[4], self.arc_vertices[idx][1])):
            r = self.port_radius[v]
            if math.hypot(bend[0] - centre[0], bend[1] - centre[1]) <= 1.02 * r:
                return False
            if (bend[0] - port[0]) * (port[0] - centre[0]) + (bend[1] - port[1]) * (port[1] - centre[1]) <= 0:
                return False
        return True

    def valid(self, moved, segments):
        """Is the current drawing valid, checking only the segments in ``moved``?"""
        moved_set = set(moved)
        if not all(self.ends_ok(idx) for idx in {idx for idx, k in moved}):
            return False
        current = {}
        for (idx, k) in moved:
            pts = self.arc_points(idx)
            current[(idx, k)] = (pts[k], pts[k + 1])
        # moved segments against the unmoved ones ...
        for (idx, k), (p, q) in current.items():
            for (idx2, k2, p2, q2) in segments:
                if (idx2, k2) in moved_set or self._adjacent(idx, k, idx2, k2):
                    continue
                if _segments_cross(p, q, p2, q2):
                    return False
        # ... and against each other (the stubs and first segments of one disk, say)
        items = list(current.items())
        for i in range(len(items)):
            (idx, k), (p, q) = items[i]
            for j in range(i + 1, len(items)):
                (idx2, k2), (p2, q2) = items[j]
                if self._adjacent(idx, k, idx2, k2):
                    continue
                if _segments_cross(p, q, p2, q2):
                    return False
        return True

    def is_planar(self):
        segments = self.segments()
        return self.valid([(idx, k) for idx in self.arcs for k in range(6)], segments) and \
            all(self.rotation_ok(v) for v in self.vertices)

    def self_crossing_bundles(self, lanes_of, edge_of):
        """The bundles (keyed as in ``lanes_of``) two of whose strands cross each other."""
        bundle_of = {}
        for e1, lanes in lanes_of.items():
            for lane in lanes:
                bundle_of[edge_of[lane]] = e1
        segments = self.segments()
        bad = set()
        for i in range(len(segments)):
            idx, k, p, q = segments[i]
            for j in range(i + 1, len(segments)):
                idx2, k2, p2, q2 = segments[j]
                if bundle_of.get(idx) != bundle_of.get(idx2) or self._adjacent(idx, k, idx2, k2):
                    continue
                if _segments_cross(p, q, p2, q2):
                    bad.add(bundle_of[idx])
        return bad

    def try_move(self, node, apply, undo, segments, touched_vertices):
        apply()
        moved = self.incident_segments(node)
        if self.valid(moved, segments) and all(self.rotation_ok(v) for v in touched_vertices):
            return True
        undo()
        return False

    def node_pos(self, node):
        if node[0] == "V":
            return self.vpos[node[1]]
        if node[0] == "D":
            return self.port(node[1])
        return self.bends[node[1]][node[2]]

    def max_step(self, node, segments):
        """A safe bound on the displacement of ``node``: a fraction of its distance to
        the nearest non-incident feature and of the distance from its incident segments
        to the nearest other node."""
        point = self.node_pos(node)
        inc = self.incident_segments(node)
        best = float("inf")
        for idx, k, p, q in segments:
            # segments sharing a node with a moving segment touch it anyway
            if any(self._adjacent(idx, k, idx2, k2) or (idx, k) == (idx2, k2) for idx2, k2 in inc):
                continue
            best = min(best, _point_segment_distance(point, p, q))
        own_nodes = set()
        for idx, k in inc:
            own_nodes |= set(self.segment_nodes(idx, k))
        for other in self.nodes:
            if other == node:
                continue
            op = self.node_pos(other)
            # no node ever reaches another one (bends of one arc included) ...
            dist = math.hypot(op[0] - point[0], op[1] - point[1])
            if dist > 1e-9:
                best = min(best, dist)
            if other in own_nodes:
                continue
            # ... and no moving segment sweeps over a node
            for idx, k in inc:
                pts = self.arc_points(idx)
                best = min(best, _point_segment_distance(op, pts[k], pts[k + 1]))
        return 0.45 * best

    # -- forces
    def forces(self, segments):
        rho = self.rho
        F = {node: [0.0, 0.0] for node in self.nodes}   # for D nodes: [tangential force, unused]

        def push(node, fx, fy):
            F[node][0] += fx
            F[node][1] += fy

        # disks repel each other up to an ideal spacing (wider for disks joined by fat edges)
        widest = {}
        for idx, (va, vb) in self.arc_vertices.items():
            key = (min(va, vb), max(va, vb))
            widest[key] = max(widest.get(key, 0.0), self.width[idx])
        for i, v in enumerate(self.vertices):
            for w in self.vertices[i + 1:]:
                dx, dy = self.vpos[v][0] - self.vpos[w][0], self.vpos[v][1] - self.vpos[w][1]
                d = math.hypot(dx, dy) + 1e-9
                ideal = 5.0 * rho + 2.0 * widest.get((min(v, w), max(v, w)), 0.0)
                if frozenset((v, w)) in self.partners:
                    # the two feet of a handle: a spring, so that the handle is short
                    ideal = 3.4 * rho + 2.0 * widest.get((min(v, w), max(v, w)), 0.0)
                    f = 0.8 * (ideal - d) / d
                    push(("V", v), f * dx, f * dy)
                    push(("V", w), -f * dx, -f * dy)
                elif d < ideal:
                    f = 0.5 * (ideal - d) / d
                    push(("V", v), f * dx, f * dy)
                    push(("V", w), -f * dx, -f * dy)
        # the chords joining the two feet of a handle (where the handle will be drawn)
        # keep clear of other disks and of each other, so that handles neither pass over
        # other handles' feet nor cross
        chords = [tuple(pair) for pair in self.partners if all(v in self.vpos for v in pair)]
        for (a, b) in chords:
            pa, pb = self.vpos[a], self.vpos[b]
            for v in self.vertices:
                if v in (a, b):
                    continue
                closest, t = _closest_point_on_segment(self.vpos[v], pa, pb)
                dx, dy = self.vpos[v][0] - closest[0], self.vpos[v][1] - closest[1]
                d = math.hypot(dx, dy)
                clearance = 3.2 * rho
                if 1e-12 < d < clearance:
                    f = 0.6 * (clearance - d) / d
                    push(("V", v), f * dx, f * dy)
                    push(("V", a), -0.5 * f * (1 - t) * dx, -0.5 * f * (1 - t) * dy)
                    push(("V", b), -0.5 * f * t * dx, -0.5 * f * t * dy)
        for i, (a, b) in enumerate(chords):
            for (c, e) in chords[i + 1:]:
                ma = ((self.vpos[a][0] + self.vpos[b][0]) / 2, (self.vpos[a][1] + self.vpos[b][1]) / 2)
                mc = ((self.vpos[c][0] + self.vpos[e][0]) / 2, (self.vpos[c][1] + self.vpos[e][1]) / 2)
                la = math.hypot(self.vpos[a][0] - self.vpos[b][0], self.vpos[a][1] - self.vpos[b][1])
                lc = math.hypot(self.vpos[c][0] - self.vpos[e][0], self.vpos[c][1] - self.vpos[e][1])
                dx, dy = ma[0] - mc[0], ma[1] - mc[1]
                d = math.hypot(dx, dy) + 1e-9
                ideal = 0.5 * (la + lc) + 2.0 * rho
                if d < ideal:
                    f = 0.3 * (ideal - d) / d
                    for v in (a, b):
                        push(("V", v), f * dx, f * dy)
                    for v in (c, e):
                        push(("V", v), -f * dx, -f * dy)
        # bends are drawn to the midpoint of their neighbours: arcs become smooth and short
        for idx in self.arcs:
            pts = self.arc_points(idx)
            for k in range(3):
                mx, my = (pts[k + 1][0] + pts[k + 3][0]) / 2, (pts[k + 1][1] + pts[k + 3][1]) / 2
                push(("B", idx, k), 0.5 * (mx - pts[k + 2][0]), 0.5 * (my - pts[k + 2][1]))
        # a port turns towards the first bend of its arc, so that arcs leave radially
        for idx in self.arcs:
            pts = self.arc_points(idx)
            for e, b, c in ((self.arc_darts[idx][0], pts[2], pts[0]), (self.arc_darts[idx][1], pts[4], pts[6])):
                want = math.atan2(b[1] - c[1], b[0] - c[0])
                diff = (want - self.angles[e] + math.pi) % (2 * math.pi) - math.pi
                push(("D", e), 0.5 * diff, 0.0)
        # disks push segments away (and are pushed back by arcs that are not theirs)
        for v in self.vertices:
            cx, cy = self.vpos[v]
            for idx, k, p, q in segments:
                own = v in self.arc_vertices[idx]
                if own and k in (0, 5):
                    continue
                clearance = 1.9 * rho if own else 1.4 * rho + self.width[idx]
                closest, t = _closest_point_on_segment((cx, cy), p, q)
                d = math.hypot(cx - closest[0], cy - closest[1])
                if 1e-12 < d < clearance:
                    nx, ny = (cx - closest[0]) / d, (cy - closest[1]) / d
                    f = 0.8 * (clearance - d)
                    for name, wgt in zip(self.segment_nodes(idx, k), (1 - t, t)):
                        if name[0] == "B":
                            push(name, -f * wgt * nx, -f * wgt * ny)
                    if not own:
                        push(("V", v), 0.5 * f * nx, 0.5 * f * ny)
        # bends keep a gap to other arcs
        for idx in self.arcs:
            for k in range(3):
                b = self.bends[idx][k]
                for idx2, k2, p, q in segments:
                    if idx2 == idx:
                        continue
                    gap = 0.8 * rho + self.width[idx] + self.width[idx2]
                    closest, _ = _closest_point_on_segment(b, p, q)
                    d = math.hypot(b[0] - closest[0], b[1] - closest[1])
                    if 1e-12 < d < gap:
                        f = 0.4 * (gap - d) / d
                        push(("B", idx, k), f * (b[0] - closest[0]), f * (b[1] - closest[1]))
        # the port of a sheet at a_i-bar mirrors the port of the same sheet at a_i across
        # the chord of the handle, so that the strand over the handle need not twist
        if self.sheet_partner:
            for (a, b) in chords:
                pa, pb = self.vpos[a], self.vpos[b]
                theta_u = math.atan2(pb[1] - pa[1], pb[0] - pa[0])
                for e in self.vertex_darts[a]:
                    f = self.sheet_partner.get(e)
                    if f is None or f not in self.angles:
                        continue
                    want_f = 2 * theta_u + math.pi - self.angles[e]
                    diff = (want_f - self.angles[f] + math.pi) % (2 * math.pi) - math.pi
                    push(("D", f), 0.3 * diff, 0.0)
                    push(("D", e), -0.3 * diff, 0.0)
        # the ports of a disk spread out around it, fat edges taking a larger share
        for v in self.vertices:
            darts = self.vertex_darts[v]
            n = len(darts)
            if n < 2:
                continue
            total = sum(self.lane_count.get(e, 1) for e in darts)
            for i in range(n):
                e1, e2 = darts[i], darts[(i + 1) % n]
                want = 0.7 * 2 * math.pi * (self.lane_count.get(e1, 1) + self.lane_count.get(e2, 1)) / 2 / total
                g = (self.angles[e2] - self.angles[e1]) % (2 * math.pi)
                if g < want:
                    f = 0.5 * (want - g)
                    push(("D", e1), -f, 0.0)
                    push(("D", e2), f, 0.0)
        # weak centring keeps the drawing from drifting
        for v in self.vertices:
            x, y = self.vpos[v]
            push(("V", v), -0.02 * x, -0.02 * y)
        for idx in self.arcs:
            for k in range(3):
                x, y = self.bends[idx][k]
                push(("B", idx, k), -0.02 * x, -0.02 * y)
        return F

    def target_radius(self, v):
        lanes = sum(self.lane_count.get(e, 1) for e in self.vertex_darts[v])
        return max(1.5 * self.rho, 1.3 * lanes * 0.8 * self.rho / (2 * math.pi))

    def run(self, iters=300):
        quiet = 0
        for it in range(iters):
            eta = 0.25 * (1 - 0.7 * it / iters)
            segments = self.segments()
            F = self.forces(segments)
            moved = 0.0          # largest move relative to the local cap
            for node in self.nodes:
                if node[0] == "D":
                    e = node[1]
                    v = self.vertex_of[e]
                    darts = self.vertex_darts[v]
                    i = darts.index(e)
                    old = self.angles[e]
                    delta = eta * F[node][0]
                    if len(darts) > 1:
                        before = (old - self.angles[darts[i - 1]]) % (2 * math.pi)
                        after = (self.angles[darts[(i + 1) % len(darts)]] - old) % (2 * math.pi)
                        cap = 0.45 * (before if delta < 0 else after)
                        delta = max(-cap, min(cap, delta))
                    delta = max(-0.3, min(0.3, delta))
                    for _ in range(6):
                        def apply(e=e, a=old + delta):
                            self.angles[e] = a

                        def undo(e=e, a=old):
                            self.angles[e] = a
                        if self.try_move(node, apply, undo, segments, [v]):
                            moved = max(moved, abs(delta) / 0.3)
                            segments = self.segments()
                            break
                        delta /= 2
                    continue
                x, y = self.node_pos(node)
                mx, my = eta * F[node][0], eta * F[node][1]
                m = math.hypot(mx, my)
                if m < 1e-12:
                    continue
                cap = min(0.15, self.max_step(node, segments))
                if m > cap:
                    mx, my = mx * cap / m, my * cap / m
                for _ in range(6):
                    newpos = (x + mx, y + my)

                    def apply(node=node, p=newpos):
                        self._set(node, p)

                    def undo(node=node, p=(x, y)):
                        self._set(node, p)
                    touched = [node[1]] if node[0] == "V" else []
                    if self.try_move(node, apply, undo, segments, touched):
                        moved = max(moved, math.hypot(mx, my) / (cap + 1e-12))
                        segments = self.segments()
                        break
                    mx, my = mx / 2, my / 2
            # inflate the ports, never beyond the first bends of the disk's own arcs
            for v in self.vertices:
                r = self.port_radius[v]
                target = self.target_radius(v)
                if r >= target:
                    continue
                cx, cy = self.vpos[v]
                nearest_bend = target / 0.7
                for e in self.vertex_darts[v]:
                    idx = self.edge_of[e]
                    b = self.bends[idx][0] if self.arc_darts[idx][0] == e else self.bends[idx][2]
                    nearest_bend = min(nearest_bend, math.hypot(b[0] - cx, b[1] - cy))
                new = min(target, r * 1.15 + 0.002 * self.rho, 0.7 * nearest_bend)
                if new <= r:
                    continue
                self.port_radius[v] = new
                if not self.valid(self.incident_segments(("V", v)), segments):
                    self.port_radius[v] = r
                else:
                    moved = max(moved, (new - r) / r)
                    segments = self.segments()
            quiet = quiet + 1 if moved < 0.02 else 0
            if it > 60 and quiet >= 10:
                break

    def _set(self, node, p):
        if node[0] == "V":
            self.vpos[node[1]] = p
        else:
            self.bends[node[1]][node[2]] = p


# --------------------------------------------------------------------------- the diagram

class HeegaardDiagram:
    """The planar Heegaard diagram given by a configuration (p, A', B, C) of Neuwirth's
    algorithm for the presentation ``gens``, ``rels`` (same input format as
    ``neuwirthcheck.check_presentation``)."""

    def __init__(self, gens, rels, p, A, B, C, relax_iterations=300):
        self.gens = gens
        self.rels = rels
        self.g = len(gens)
        self.prev = nw.prevalences(gens, rels)
        self.n = sum(self.prev)
        N = self.N = 2 * self.n
        self.p, self.A, self.B, self.C = p, A, B, C
        darts = self.darts = list(range(1, N + 1))
        self.Amap = {e: A(e) for e in darts}
        self.Cmap = {e: C(e) for e in darts}
        self.Cinv = {v: k for k, v in self.Cmap.items()}

        # dart -> (generator index, sheet number, barred)
        offsets = [sum(self.prev[:i]) for i in range(self.g)]
        self.dart_info = {}
        for e in darts:
            barred = e > self.n
            x = e - self.n if barred else e
            i = max(k for k in range(self.g) if offsets[k] < x)
            self.dart_info[e] = (i, x - offsets[i], barred)
        # vertex (disk) of a dart: 2*i for the disk a_i, 2*i+1 for the disk a_i-bar
        self.vertex_of = {e: 2 * info[0] + (1 if info[2] else 0) for e, info in self.dart_info.items()}
        self.vertices = list(range(2 * self.g))
        self.vertex_darts = {v: [] for v in self.vertices}
        for cycle in _cycles(self.Cmap, darts):
            self.vertex_darts[self.vertex_of[cycle[0]]] = cycle

        # arcs of the beta-curves, in the order in which neuwirth.admissible created them:
        # one per cyclically consecutive pair of letters, relator by relator
        pinv = p.inverse()
        original = _parse_cycles(nw.admissible(gens, rels))
        self.arcs = []
        k = 0
        for r, word in enumerate(rels):
            for t in range(len(word)):
                exit_dart, entry_dart = pinv(original[k][0]), pinv(original[k][1])
                k += 1
                if self.Amap[exit_dart] != entry_dart:
                    raise ValueError("the involution A does not match the relators")
                self.arcs.append({
                    "exit": exit_dart, "entry": entry_dart, "rel": r, "pos": t,
                    "closing": t == len(word) - 1,
                })
        self.edge_of = {}
        for idx, arc in enumerate(self.arcs):
            self.edge_of[arc["exit"]] = idx
            self.edge_of[arc["entry"]] = idx

        # faces: orbits of e -> A(C(e)); the face of a dart e is the region in the
        # sector counter-clockwise after e at its disk
        psi = {e: self.Amap[self.Cmap[e]] for e in darts}
        self.faces = _cycles(psi, darts)
        self.face_of = {}
        for fi, face in enumerate(self.faces):
            for e in face:
                self.face_of[e] = fi

        # connected components (the L orbits of <A, C>)
        self.components = _orbits([self.Amap, self.Cmap], darts)
        self.L = len(self.components)
        self.component_of = {}
        for ci, comp in enumerate(self.components):
            for e in comp:
                self.component_of[e] = ci

        # regions joined by tubes when L > 1: the AC-orbit of a dart e corresponds to the
        # region in the sector before e (see neuwirthcheck.construct_F)
        self.tube_faces = set()
        if self.L > 1:
            F = neuwirthcheck.construct_F(A, C)
            for cycle in F.to_cycles(singletons=False):
                for e in cycle:
                    self.tube_faces.add(self.face_of[self.Cinv[e]])

        self.relax_iterations = relax_iterations
        self.layouts = [self._layout(ci) for ci in range(self.L)]

    # ----------------------------------------------------------------- combinatorics

    def euler_characteristics(self):
        """(V - E + F) of every component; all equal to 2 for a Heegaard diagram."""
        result = []
        for comp in self.components:
            vs = {self.vertex_of[e] for e in comp}
            es = {self.edge_of[e] for e in comp}
            fs = {self.face_of[e] for e in comp}
            result.append(len(vs) - len(es) + len(fs))
        return result

    def vertex_label(self, v):
        return self.gens[v // 2][0], v % 2 == 1

    # ----------------------------------------------------------------- layout

    def _bundles(self, comp):
        """Maximal bundles of parallel arcs.

        The arcs of the darts e and C(e) are parallel neighbours when the face after e
        is a bigon; chains of such darts are the bundles.  Returns a list of bundles,
        each a list of darts at one disk in counter-clockwise order (one dart per arc);
        the chain at the other disk is the same bundle reversed and is not listed."""
        comp_set = set(comp)
        is_bigon = {e: len(self.faces[self.face_of[e]]) == 2 for e in comp}
        has_prev = {e: is_bigon[self.Cinv[e]] for e in comp}
        chains = []
        seen = set()
        for start in sorted(comp):
            if start in seen or (has_prev[start] and not self._whole_cycle_bigons(start)):
                continue
            chain = []
            e = start
            while e not in seen:
                seen.add(e)
                chain.append(e)
                if not is_bigon[e]:
                    break
                e = self.Cmap[e]
            chains.append(chain)
        # every bundle appears twice, once from each disk: keep one copy
        bundles = []
        taken = set()
        for chain in chains:
            arcs = frozenset(self.edge_of[e] for e in chain)
            if arcs in taken:
                continue
            taken.add(arcs)
            bundles.append(chain)
        assert sum(len(b) for b in bundles) * 2 == len(comp_set)
        return bundles

    def _whole_cycle_bigons(self, e):
        """Is every face around the disk of ``e`` a bigon (a cyclic bundle)?"""
        return all(len(self.faces[self.face_of[x]]) == 2 for x in self.vertex_darts[self.vertex_of[e]])

    def _reduced_map(self, comp):
        """Rotation system of the component with every bundle contracted to one arc.
        Returns (darts, Amap, Cmap, lane_of_bundle) where lane_of_bundle maps the kept
        exit dart of a bundle to its list of lane darts in counter-clockwise order."""
        bundles = self._bundles(comp)
        removed = set()
        lanes_of = {}
        for lanes in bundles:
            lanes_of[lanes[0]] = lanes
            for e in lanes[1:]:
                removed.add(e)
                removed.add(self.Amap[e])
        darts = [e for e in comp if e not in removed]
        Cmap = {}
        for e in darts:
            x = self.Cmap[e]
            while x in removed:
                x = self.Cmap[x]
            Cmap[e] = x
        Amap = {e: self.Amap[e] for e in darts}
        return darts, Amap, Cmap, lanes_of

    def _initial_embedding(self, darts, Amap, Cmap):
        """Tutte embedding of the second barycentric subdivision of a map given by its
        rotation system, with the star of its largest face removed and its link fixed on
        the unit circle.  Returns positions of the nodes ('V', v), ('VM', dart) and
        ('M', edge)."""
        Cinv = {v: k for k, v in Cmap.items()}
        psi = {e: Amap[Cmap[e]] for e in darts}
        faces = _cycles(psi, darts)
        face_of = {}
        for fi, face in enumerate(faces):
            for e in face:
                face_of[e] = fi
        edge_of = {e: min(e, Amap[e]) for e in darts}

        def flag_nodes(e, side):
            v = ("V", self.vertex_of[e])
            m = ("M", edge_of[e])
            if side == "after":
                corner, mf = e, ("MF", e)
            else:
                corner, mf = Cinv[e], ("MF", Amap[e])
            return v, m, ("F", face_of[corner]), ("VM", e), mf, ("VF", corner), ("T", e, side)

        triangles = []
        for e in darts:
            for side in ("after", "before"):
                v, m, f, vm, mf, vf, t = flag_nodes(e, side)
                triangles += [(v, vm, t), (vm, m, t), (m, mf, t), (mf, f, t), (f, vf, t), (vf, v, t)]
        adjacency = {}
        seen_edges = set()
        for tri in triangles:
            for a, b in ((tri[0], tri[1]), (tri[1], tri[2]), (tri[2], tri[0])):
                key = frozenset((a, b))
                if key in seen_edges:
                    continue
                seen_edges.add(key)
                adjacency.setdefault(a, []).append(b)
                adjacency.setdefault(b, []).append(a)
        outer_face = max(range(len(faces)), key=lambda fi: (len(faces[fi]), -fi))
        outer = ("F", outer_face)
        boundary = _link_cycle(triangles, outer)
        fixed = {}
        for k, node in enumerate(boundary):
            angle = 2 * math.pi * k / len(boundary)
            fixed[node] = (math.cos(angle), math.sin(angle))
        del adjacency[outer]
        for node in adjacency:
            adjacency[node] = [w for w in adjacency[node] if w != outer]
        pos = _tutte(adjacency, fixed)
        # make sure C runs counter-clockwise; mirror the drawing otherwise
        by_vertex = {}
        for cycle in _cycles(Cmap, darts):
            by_vertex[self.vertex_of[cycle[0]]] = cycle
        for v, cycle in by_vertex.items():
            if len(cycle) < 3:
                continue
            cx, cy = pos[("V", v)]
            angles = [math.atan2(pos[("VM", e)][1] - cy, pos[("VM", e)][0] - cx) for e in cycle]
            if _turning(angles) > 2 * math.pi + 1e-9:
                pos = {node: (-x, y) for node, (x, y) in pos.items()}
            break
        return pos, edge_of

    def _relaxed_drawing(self, comp, rho, iterations):
        """Planar drawing of the component: disk centres, port angles, port radii and
        three bends per arc.  The bundles are first contracted, the reduced map is
        embedded (Tutte) and relaxed with bundles as fat edges, then every bundle is
        expanded into parallel strands and the full drawing is relaxed again."""
        darts, Amap, Cmap, lanes_of = self._reduced_map(comp)
        pos, edge_of = self._initial_embedding(darts, Amap, Cmap)
        vertices = sorted({self.vertex_of[e] for e in comp})
        vpos = {v: pos[("V", v)] for v in vertices}
        # the reduced map as the relaxer wants it
        r_vertex_darts = {}
        for cycle in _cycles(Cmap, darts):
            r_vertex_darts[self.vertex_of[cycle[0]]] = cycle
        r_arc_darts = {}
        for e in darts:
            if e in lanes_of:
                r_arc_darts[e] = (e, Amap[e])      # oriented from the bundle's first dart
        lane_count = {}
        for e, lanes in lanes_of.items():
            lane_count[e] = len(lanes)
            lane_count[Amap[e]] = len(lanes)
        angles = {}
        port_radius = {}
        for v in vertices:
            cx, cy = vpos[v]
            dist = []
            for e in r_vertex_darts[v]:
                x, y = pos[("VM", e)]
                angles[e] = math.atan2(y - cy, x - cx)
                dist.append(math.hypot(x - cx, y - cy))
            port_radius[v] = 0.5 * min(dist)
        bends = {}
        for idx, (ea, eb) in r_arc_darts.items():
            bends[idx] = [pos[("VM", ea)], pos[("M", edge_of[ea])], pos[("VM", eb)]]
        partners = [(2 * i, 2 * i + 1) for i in range(self.g)]
        reduced = _Relaxer(r_vertex_darts, self.vertex_of, r_arc_darts, vpos, angles, bends, port_radius,
                           rho, lane_count, partners)
        reduced.run(iterations)

        # expand the bundles into strands
        full_arc_darts = {idx: (arc["exit"], arc["entry"]) for idx, arc in enumerate(self.arcs)
                          if arc["exit"] in set(comp)}
        full_vertex_darts = {v: self.vertex_darts[v] for v in vertices}
        delta = 0.8 * rho
        straight = set()          # bundles whose fat edge is straightened before expansion
        attempts = 0
        while True:
            attempts += 1
            f_angles = {}
            f_bends = {}
            for e1, lanes in lanes_of.items():
                k = len(lanes)
                pts = reduced.arc_points(e1)[1:6]      # port, b1, b2, b3, port
                if e1 in straight:
                    p0, p4 = pts[0], pts[4]
                    pts = [p0] + [(p0[0] + (p4[0] - p0[0]) * q / 4, p0[1] + (p4[1] - p0[1]) * q / 4)
                                  for q in (1, 2, 3)] + [p4]
                v, w = reduced.arc_vertices[e1]
                rv, rw = reduced.port_radius[v], reduced.port_radius[w]
                normals = []
                for i in range(1, 4):
                    dx, dy = pts[i + 1][0] - pts[i - 1][0], pts[i + 1][1] - pts[i - 1][1]
                    d = math.hypot(dx, dy) + 1e-12
                    normals.append((-dy / d, dx / d))

                def room(dart, vertex):
                    ds = reduced.vertex_darts[vertex]
                    if len(ds) == 1:
                        return 2 * math.pi
                    i = ds.index(dart)
                    a = reduced.angles[dart]
                    before = (a - reduced.angles[ds[i - 1]]) % (2 * math.pi)
                    after = (reduced.angles[ds[(i + 1) % len(ds)]] - a) % (2 * math.pi)
                    return min(before, after)

                # angular steps between neighbouring strands at both ports: the strands
                # are delta apart where there is room, and fan in where there is not
                dtheta_v = min(math.asin(min(1.0, delta / rv)), 0.8 * room(e1, v) / max(k - 1, 1))
                dtheta_w = min(math.asin(min(1.0, delta / rw)), 0.8 * room(Amap[e1], w) / max(k - 1, 1))
                for j, lane in enumerate(lanes):
                    t = j - (k - 1) / 2
                    off_v = rv * math.sin(t * dtheta_v)
                    off_w = rw * math.sin(t * dtheta_w)
                    b = []
                    for i in range(3):
                        off = off_v + (off_w - off_v) * (i + 1) / 4
                        b.append((pts[i + 1][0] + off * normals[i][0], pts[i + 1][1] + off * normals[i][1]))
                    idx = self.edge_of[lane]
                    f_bends[idx] = b if self.arcs[idx]["exit"] == lane else b[::-1]
                    f_angles[lane] = reduced.angles[e1] + t * dtheta_v
                    f_angles[self.Amap[lane]] = reduced.angles[Amap[e1]] - t * dtheta_w
            sheet_partner = {e: self.B(e) for e in comp}
            full = _Relaxer(full_vertex_darts, self.vertex_of, full_arc_darts, dict(reduced.vpos), f_angles,
                            f_bends, dict(reduced.port_radius), rho, partners=partners,
                            sheet_partner=sheet_partner)
            if full.is_planar() or delta < 1e-7:
                break
            # a bundle whose strands cross each other has a fat edge that bends too sharply
            # for the strand spacing: straighten it before shrinking the spacing
            bad = full.self_crossing_bundles(lanes_of, self.edge_of)
            fresh = bad - straight
            if fresh and attempts < 8:
                straight |= fresh
                continue
            delta /= 2
        full.run(max(iterations // 2, 60))
        return vertices, full

    def _layout(self, ci):
        comp = self.components[ci]
        comp_faces = sorted({self.face_of[e] for e in comp}, key=lambda fi: (-len(self.faces[fi]), fi))
        rho = 0.12
        vertices, relaxer = self._relaxed_drawing(comp, rho, self.relax_iterations)

        # rotate so that the longest extent is horizontal (a rotation keeps the
        # orientation), then normalise to the unit box
        allpts = list(relaxer.vpos.values()) + [p for b in relaxer.bends.values() for p in b]
        mx = sum(p[0] for p in allpts) / len(allpts)
        my = sum(p[1] for p in allpts) / len(allpts)
        sxx = sum((p[0] - mx) ** 2 for p in allpts)
        syy = sum((p[1] - my) ** 2 for p in allpts)
        sxy = sum((p[0] - mx) * (p[1] - my) for p in allpts)
        theta = -0.5 * math.atan2(2 * sxy, sxx - syy) if len(allpts) > 1 else 0.0
        ct, st = math.cos(theta), math.sin(theta)

        def rot(p):
            x, y = p[0] - mx, p[1] - my
            return (ct * x - st * y, st * x + ct * y)

        allpts = [rot(p) for p in allpts]
        xs = [p[0] for p in allpts]
        ys = [p[1] for p in allpts]
        cx, cy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
        scale = max(max(xs) - min(xs), max(ys) - min(ys), 1e-9) / 2
        margin = 1.0 + 1.3 * rho / scale

        def N(p):
            q = rot(p)
            return ((q[0] - cx) / scale / margin, (q[1] - cy) / scale / margin)

        centres = {v: N(p) for v, p in relaxer.vpos.items()}
        rho_n = rho / scale / margin
        dart_angle = {e: a + theta for e, a in relaxer.angles.items()}
        radii = {v: 0.6 * relaxer.port_radius[v] / scale / margin for v in vertices}
        edges = {}
        for idx, b in relaxer.bends.items():
            va, vb = relaxer.arc_vertices[idx]
            ea, eb = relaxer.arc_darts[idx]
            edges[idx] = ([centres[va], N(relaxer.port(ea))] + [N(p) for p in b]
                          + [N(relaxer.port(eb)), centres[vb]])

        # a point inside each inner face, for markers: just outside a disk, in the
        # middle of the widest sector of the face
        face_points = {}
        for fi in comp_faces[1:]:
            best = None
            for e in self.faces[fi]:
                v = self.vertex_of[e]
                a1, a2 = dart_angle[e], dart_angle[self.Cmap[e]]
                gap = (a2 - a1) % (2 * math.pi)
                if len(self.vertex_darts[v]) == 1:
                    gap = 2 * math.pi
                if best is None or gap > best[0]:
                    best = (gap, v, a1 + gap / 2)
            gap, v, ang = best
            r = radii[v] + 1.2 * rho_n
            face_points[fi] = (centres[v][0] + r * math.cos(ang), centres[v][1] + r * math.sin(ang))
        return {
            "vertices": vertices, "centres": centres, "radii": radii, "edges": edges,
            "dart_angle": dart_angle, "faces": comp_faces, "outer": comp_faces[0],
            "face_points": face_points, "rho": rho_n,
        }

    # ----------------------------------------------------------------- geometry for rendering

    def _curves(self, layout, smooth=True):
        """Polylines (in layout coordinates) for the arcs of one component, trimmed to the
        disk boundaries, as a dict edge index -> list of points (from exit to entry)."""
        curves = {}
        for idx, pts in layout["edges"].items():
            arc = self.arcs[idx]
            va, vb = self.vertex_of[arc["exit"]], self.vertex_of[arc["entry"]]
            trimmed = list(pts)
            for end, v in ((0, va), (-1, vb)):
                cx, cy = layout["centres"][v]
                nx, ny = trimmed[1 if end == 0 else -2]
                d = math.hypot(nx - cx, ny - cy)
                r = layout["radii"][v]
                trimmed[end] = (cx + r * (nx - cx) / d, cy + r * (ny - cy) / d)
            curves[idx] = trimmed
        if smooth:
            smoothed = {idx: _chaikin(pts) for idx, pts in curves.items()}
            if self._count_crossings(smoothed) == 0:
                return smoothed
        return curves

    @staticmethod
    def _count_crossings(curves):
        segs = []
        for idx, pts in curves.items():
            segs += [(idx, a, b) for a, b in zip(pts, pts[1:])]
        total = 0
        for i in range(len(segs)):
            for j in range(i + 1, len(segs)):
                if segs[i][0] != segs[j][0] and _segments_cross(segs[i][1], segs[i][2], segs[j][1], segs[j][2]):
                    total += 1
        return total

    def crossings(self):
        """Number of pairs of rendered arcs that cross; 0 for a valid drawing."""
        return sum(self._count_crossings(self._curves(layout)) for layout in self.layouts)

    def rotations_ok(self):
        """Do the rendered arcs leave every disk in the cyclic order C?"""
        for layout in self.layouts:
            for v in layout["vertices"]:
                darts = self.vertex_darts[v]
                if len(darts) >= 3:
                    angles = [layout["dart_angle"][e] for e in darts]
                    if abs(_turning(angles) - 2 * math.pi) > 1e-9:
                        return False
        return True

    def _label_arcs(self):
        """The arc on which the label of each beta-curve is written: its longest arc."""
        best = {}
        for layout in self.layouts:
            for idx, pts in layout["edges"].items():
                r = self.arcs[idx]["rel"]
                length = _polyline_length(pts)
                if r not in best or length > best[r][0]:
                    best[r] = (length, idx)
        return {idx for _, idx in best.values()}

    # ----------------------------------------------------------------- text

    def presentation_text(self, latex=False):
        def word(w):
            out = []
            k = 0
            while k < len(w):
                letter = w[k]
                j = k
                while j < len(w) and w[j] == letter:
                    j += 1
                count = j - k
                base = letter.lower()
                exponent = count if letter.islower() else -count
                if latex:
                    out.append(base if exponent == 1 else "%s^{%d}" % (base, exponent))
                else:
                    out.append(base if exponent == 1 else "%s^%d" % (base, exponent))
                k = j
            return "".join(out) if latex else " ".join(out)
        gens = ", ".join(g[0] for g in self.gens)
        rels = ", ".join(word(w) for w in self.rels)
        if latex:
            return r"\langle %s \mid %s \rangle" % (gens, rels)
        return "<%s | %s>" % (gens, rels)

    # ----------------------------------------------------------------- SVG

    PALETTE = ["#d62728", "#1f77b4", "#2ca02c", "#9467bd", "#ff7f0e", "#17becf", "#8c564b", "#e377c2"]

    def to_svg(self, width=560, height=440, margin=24, standalone=True):
        """The diagram as an SVG string (one panel per component, side by side)."""
        label_arcs = self._label_arcs()
        panels = []
        x = margin
        for ci, layout in enumerate(self.layouts):
            panels.append(self._svg_panel(layout, width, height, x + width / 2, margin + height / 2, label_arcs))
            x += width + margin
        total_h = height + 2 * margin
        parts = []
        if standalone:
            parts.append('<?xml version="1.0" encoding="UTF-8"?>')
        parts.append('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" '
                     'font-family="Helvetica, Arial, sans-serif">' % (x, total_h, x, total_h))
        parts.append('<rect width="100%" height="100%" fill="white"/>')
        parts += panels
        parts.append("</svg>")
        return "\n".join(parts)

    def _svg_panel(self, layout, width, height, cx0, cy0, label_arcs):
        # fit the drawing (which was rotated to be wide) into the panel
        xs = [p[0] for pts in layout["edges"].values() for p in pts] + [c[0] for c in layout["centres"].values()]
        ys = [p[1] for pts in layout["edges"].values() for p in pts] + [c[1] for c in layout["centres"].values()]
        wx = max(xs) - min(xs) + 2.6 * layout["rho"]
        wy = max(ys) - min(ys) + 2.6 * layout["rho"]
        s = min((width - 8) / max(wx, 1e-9), (height - 8) / max(wy, 1e-9))
        mx, my = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2

        def P(pt):
            return (cx0 + s * (pt[0] - mx), cy0 - s * (pt[1] - my))   # flip y: C stays counter-clockwise

        out = ['<g>']
        curves = self._curves(layout)
        for idx, pts in curves.items():
            arc = self.arcs[idx]
            colour = self.PALETTE[arc["rel"] % len(self.PALETTE)]
            path = "M " + " L ".join("%.2f %.2f" % P(p) for p in pts)
            out.append('<path d="%s" fill="none" stroke="%s" stroke-width="2" stroke-linejoin="round" '
                       'stroke-linecap="round"/>' % (path, colour))
            screen = [P(p) for p in pts]
            (ax, ay), (tx, ty) = _polyline_point(screen, 0.5)
            out.append(self._svg_arrow(ax, ay, tx, ty, colour))
            if arc["closing"]:
                (bx, by), _ = _polyline_point(screen, 0.72)
                out.append('<circle cx="%.2f" cy="%.2f" r="4" fill="%s"/>' % (bx, by, colour))
            if idx in label_arcs:
                (lx, ly), (tx, ty) = _polyline_point(screen, 0.3)
                lx, ly = lx - 12 * ty, ly + 12 * tx
                out.append('<text x="%.2f" y="%.2f" font-size="15" font-style="italic" fill="%s" '
                           'text-anchor="middle" dominant-baseline="middle">&#946;<tspan font-size="10" '
                           'baseline-shift="sub">%d</tspan></text>' % (lx, ly, colour, arc["rel"] + 1))
        for fi in layout["faces"]:
            if fi not in self.tube_faces:
                continue
            if fi == layout["outer"]:
                x, y = cx0 - width / 2 + 16, cy0 - height / 2 + 10
            else:
                x, y = P(layout["face_points"][fi])
            out.append('<text x="%.2f" y="%.2f" font-size="28" text-anchor="middle" dominant-baseline="middle" '
                       'fill="#444">&#8727;</text>' % (x, y))
        for v in layout["vertices"]:
            cx, cy = P(layout["centres"][v])
            r = s * layout["radii"][v]
            letter, barred = self.vertex_label(v)
            out.append('<circle cx="%.2f" cy="%.2f" r="%.2f" fill="#f4f4f4" stroke="#222" stroke-width="2"/>'
                       % (cx, cy, r))
            fs = max(11, min(24, r * 0.95))
            out.append('<text x="%.2f" y="%.2f" font-size="%.1f" font-style="italic" text-anchor="middle" '
                       'dominant-baseline="middle">%s</text>' % (cx, cy + fs * 0.06, fs, html.escape(letter)))
            if barred:
                out.append('<line x1="%.2f" y1="%.2f" x2="%.2f" y2="%.2f" stroke="#222" stroke-width="1.3"/>'
                           % (cx - fs * 0.3, cy - fs * 0.52, cx + fs * 0.3, cy - fs * 0.52))
            for e in self.vertex_darts[v]:
                ang = layout["dart_angle"][e]
                j = self.dart_info[e][1]
                lr = r + 9
                lx = cx + lr * math.cos(ang) + 7 * math.sin(ang)
                ly = cy - lr * math.sin(ang) + 7 * math.cos(ang)
                out.append('<text x="%.2f" y="%.2f" font-size="9" fill="#555" text-anchor="middle" '
                           'dominant-baseline="middle">%d</text>' % (lx, ly, j))
        out.append("</g>")
        return "\n".join(out)

    @staticmethod
    def _svg_arrow(x, y, tx, ty, colour, size=7):
        nx, ny = -ty, tx
        p1 = (x + size * tx, y + size * ty)
        p2 = (x - size * 0.6 * tx + size * 0.55 * nx, y - size * 0.6 * ty + size * 0.55 * ny)
        p3 = (x - size * 0.6 * tx - size * 0.55 * nx, y - size * 0.6 * ty - size * 0.55 * ny)
        return '<polygon points="%.2f,%.2f %.2f,%.2f %.2f,%.2f" fill="%s"/>' % (p1 + p2 + p3 + (colour,))

